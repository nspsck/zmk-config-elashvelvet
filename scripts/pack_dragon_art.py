#!/usr/bin/env python3
"""Encode the approved 2x2 artwork sheet as four firmware-ready 1-bit frames.

Requires ImageMagick 7 (`magick`). This is an asset build step: area-sample the
generated sheet to its native resolution, then pack rows without dithering.
The generated C is committed, so firmware builds do not need ImageMagick.
"""
from pathlib import Path
import hashlib
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/display/dragon-source.png"
WIDTH, HEIGHT, COUNT = 64, 52, 4
STRIDE = WIDTH // 8


def main():
    samples = subprocess.check_output([
        "magick", str(SOURCE), "-alpha", "off", "-colorspace", "Gray",
        "-filter", "Box", "-resize", "128x104!", "-threshold", "50%",
        "-depth", "8", "gray:-",
    ])
    assert len(samples) == WIDTH * 2 * HEIGHT * 2
    frames = []
    for index in range(COUNT):
        x0, y0 = (index % 2) * WIDTH, (index // 2) * HEIGHT
        packed = bytearray()
        for y in range(HEIGHT):
            for byte in range(STRIDE):
                value = 0
                for bit in range(8):
                    value |= (samples[(y0 + y) * WIDTH * 2 + x0 + byte * 8 + bit] > 127) << (7 - bit)
                packed.append(value)
        assert any(packed), "Empty sprite"
        frames.append(packed)
    assert len({bytes(frame) for frame in frames}) == COUNT, "Animation frames must differ"
    target = ROOT / "src/display"
    target.mkdir(parents=True, exist_ok=True)
    (target / "dragon_assets.h").write_text('''/* Generated by scripts/pack_dragon_art.py; see assets/display/README.md. */
#ifndef VELVET_DRAGON_ASSETS_H
#define VELVET_DRAGON_ASSETS_H
#include <stdint.h>
#define VELVET_DRAGON_WIDTH 64
#define VELVET_DRAGON_HEIGHT 52
#define VELVET_DRAGON_FRAME_COUNT 4
#define VELVET_DRAGON_FRAME_BYTES 416
/* Row-major, MSB-first, bit 1 = physically white. */
extern const uint8_t velvet_dragon_frames[VELVET_DRAGON_FRAME_COUNT][VELVET_DRAGON_FRAME_BYTES];
#endif
''')
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    lines = ["/* Generated by scripts/pack_dragon_art.py. Do not edit by hand.",
             f" * Source SHA-256: {digest}", " */", '#include "dragon_assets.h"', "",
             "const uint8_t velvet_dragon_frames[VELVET_DRAGON_FRAME_COUNT][VELVET_DRAGON_FRAME_BYTES] = {"]
    for name, frame in zip(("idle", "blink", "tail", "wave"), frames):
        lines.append(f"    {{ /* {name} */")
        for offset in range(0, len(frame), 16):
            lines.append("        " + ", ".join(f"0x{v:02x}" for v in frame[offset:offset + 16]) + ",")
        lines.append("    },")
    lines.append("};\n")
    (target / "dragon_assets.c").write_text("\n".join(lines))
    print(f"Packed {COUNT} frames, {WIDTH}x{HEIGHT}, {len(frames[0]) * COUNT} bytes total")


if __name__ == "__main__":
    main()
